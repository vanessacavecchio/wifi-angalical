export const CARD_KEYS = Object.keys(ANGEL_NUMBERS)

export function getRandomCard() {
  return CARD_KEYS[Math.floor(Math.random() * CARD_KEYS.length)]
}

export function getDailyCard() {
  const d = new Date()
  return CARD_KEYS[(d.getDate() + d.getMonth() * 3) % CARD_KEYS.length]
}

export function searchOracle(query) {
  const v = query.trim().replace(/\s/g, '')
  if (!v) return null

  if (ANGEL_NUMBERS[v]) return { type: 'number', key: v, data: ANGEL_NUMBERS[v] }
  if (MIRROR_HOURS[v]) return { type: 'hour', key: v, data: MIRROR_HOURS[v] }

  // "1111" → "11:11"
  if (v.length === 4) {
    const k = v.slice(0, 2) + ':' + v.slice(2)
    if (MIRROR_HOURS[k]) return { type: 'hour', key: k, data: MIRROR_HOURS[k] }
  }

  return { type: 'notfound' }
}
